/* ------------------------------------------------------------------ *
 * Certificate marks — simplified, single-colour redraws of the badges
 * shown in the "Наши международный сертификаты" row.
 * ------------------------------------------------------------------ */

function StarRing({ count = 12, r = 30 }: { count?: number; r?: number }) {
  return (
    <g fill="#fff">
      {Array.from({ length: count }).map((_, i) => {
        const angle = (i / count) * Math.PI * 2 - Math.PI / 2;
        const x = 40 + Math.cos(angle) * r;
        const y = 40 + Math.sin(angle) * r;
        return (
          <path
            key={i}
            transform={`translate(${x.toFixed(2)} ${y.toFixed(2)}) scale(0.28) translate(-12 -12)`}
            d="m12 2.6 2.9 6.03 6.6.9-4.8 4.6 1.18 6.55L12 17.6l-5.88 3.08L7.3 14.13 2.5 9.53l6.6-.9L12 2.6Z"
          />
        );
      })}
    </g>
  );
}

